#!/usr/bin/env python3
"""Emit small finite-field certificates; Lean separately checks them in its kernel.

This script discovers fixed evaluation rows and source-moment columns and emits
right inverses modulo 11. Its output is untrusted data: generated Lean row proofs
check the displayed model formulas and AB = I by ordinary kernel reduction.
Each independently cached chunk contains at most four rows. Within each row,
scalar entries are checked separately by the kernel. No external determinant
result is assumed.
"""
from pathlib import Path
import argparse
import itertools
import exact_q3t4 as model

PRIME = 11
ROOT = Path(__file__).resolve().parents[1]
ROWS_PER_CHUNK = 4
CHUNK_DIRECTORY = Path('formal/PanelMoments/WitnessChunks')
DATA_DIRECTORY = Path('formal/PanelMoments/WitnessData')


def inverse(a):
    n = len(a)
    aug = [[x % PRIME for x in row] + [int(i == j) for j in range(n)]
           for i, row in enumerate(a)]
    for j in range(n):
        k = next(k for k in range(j, n) if aug[k][j])
        aug[j], aug[k] = aug[k], aug[j]
        unit = pow(aug[j][j], -1, PRIME)
        aug[j] = [x * unit % PRIME for x in aug[j]]
        for i in range(n):
            if i != j:
                factor = aug[i][j]
                aug[i] = [(x - factor * y) % PRIME for x, y in zip(aug[i], aug[j])]
    result = [row[n:] for row in aug]
    assert all(sum(a[i][k] * result[k][j] for k in range(n)) % PRIME == int(i == j)
               for i in range(n) for j in range(n))
    return result


def reduced_value(point, path):
    effects = (1,) + tuple(point)
    value = 1
    for t, q in enumerate(path):
        value *= effects[q]
        if t:
            for r in range(3):
                if r != path[t - 1]:
                    value *= sum(model.PI[t][s][r] * effects[s] for s in range(3))
    return value % PRIME


def vector(xs):
    return '![' + ', '.join(map(str, xs)) + ']'


def matrix(rows):
    return '![' + ',\n   '.join(vector(row) for row in rows) + ']'


def source_row(index):
    """Match SourceIndex's (shared slot, second value, first value) convention."""
    if index['j'] == 0:
        return f'.inl ({index["s2"] - 1}, {index["values"][0]})'
    assert index['j'] == 1
    return (f'.inr ({index["shared"][0]}, '
            f'{index["values"][0]}, {index["values"][1]})')


def data_definitions():
    points = list(itertools.product(range(1, 11), repeat=2))
    values = [[reduced_value(point, path) for path in model.PATHS] for point in points]
    rows, cols = model.pivot_minor(values, PRIME)
    assert len(rows) == 48
    minor = [[values[i][j] for j in cols] for i in rows]
    output = [f'def evaluationPoints : Fin 48 → Fin 2 → ℕ :=\n  {matrix([points[i] for i in rows])}\n\n',
              f'def evaluationPaths : Fin 48 → Path 2 4 :=\n  {matrix([model.PATHS[j] for j in cols])}\n\n',
              f'def evaluationResidue : Matrix (Fin 48) (Fin 48) (ZMod 11) :=\n  {matrix(minor)}\n\n',
              f'def evaluationInverse : Matrix (Fin 48) (Fin 48) (ZMod 11) :=\n  {matrix(inverse(minor))}\n\n']
    for initial in range(3):
        values = model.moment_numerators(model.PI, initial)
        r, c = model.pivot_minor(values, PRIME)
        assert len(r) == 33
        # Retain the original source ordering; all 33 rows are independent.
        minor = [[values[i][j] % PRIME for j in c] for i in range(33)]
        output += [f'def sourcePaths{initial} : Fin 33 → Path 2 4 :=\n  {matrix([model.PATHS[j] for j in c])}\n\n',
                   f'def sourceResidue{initial} : Matrix (Fin 33) (Fin 33) (ZMod 11) :=\n  {matrix(minor)}\n\n',
                   f'def sourceInverse{initial} : Matrix (Fin 33) (Fin 33) (ZMod 11) :=\n  {matrix(inverse(minor))}\n\n']
    return output


def data_name(definition):
    name = definition.split()[1]
    return name[0].upper() + name[1:]


def render_data_module(definition):
    return '''import PanelMoments.Model
import Mathlib.Data.ZMod.Basic
import Mathlib.LinearAlgebra.Matrix.Notation

set_option autoImplicit false
set_option Elab.async false

/-!
# Untrusted, reproducible certificate data

Generated by `exploration/generate_lean_witness.py`. Matrix entries and inverses
are in ZMod 11. No mathematical assertion is assumed here: `Witness.lean`
checks both the primitive-formula bridge and each inverse identity in the kernel,
one row at a time through the independently cached `WitnessChunks` modules.
The evaluation witness uses positive integer effects from {1,...,10} squared.
-/

namespace PanelMoments.Witness

''' + definition + 'end PanelMoments.Witness\n'


def data_module_names():
    return ([f'PanelMoments.WitnessData.{data_name(definition)}'
             for definition in data_definitions()] + ['PanelMoments.WitnessData'])


def render_data_facade():
    return ('\n'.join(f'import {module}' for module in data_module_names()[:-1]) +
            '\n\n/-! Generated certificate data imports. Build the modules listed by\n'
            '`generate_lean_witness.py --list-data-modules` sequentially. -/\n')


def render_rows():
    return '''import PanelMoments.SourceMoments

set_option autoImplicit false

/-!
Generated by `exploration/generate_lean_witness.py`. The enumeration follows the
source family: two first-marginal contrasts, then three shared-prefix contrasts,
with every outcome value included. `WitnessCore` checks that it is bijective.
-/

namespace PanelMoments.Witness

''' + f'def sourceRows : Fin 33 → SourceIndex 2 :=\n  {vector([source_row(i) for i in model.source_indices()])}\n\n' + '''end PanelMoments.Witness
'''


def chunk_specs():
    for start in range(0, 48, ROWS_PER_CHUNK):
        yield dict(name=f'Evaluation{start // ROWS_PER_CHUNK:02}',
                   prefix='evaluation', initial=None, size=48,
                   start=start, stop=min(start + ROWS_PER_CHUNK, 48))
    for initial in range(3):
        for start in range(0, 33, ROWS_PER_CHUNK):
            yield dict(name=f'Source{initial}_{start // ROWS_PER_CHUNK:02}',
                       prefix=f'source{initial}', initial=initial, size=33,
                       start=start, stop=min(start + ROWS_PER_CHUNK, 33))


def chunk_module(spec):
    return f'PanelMoments.WitnessChunks.{spec["name"]}'


def sequential_modules():
    # The caller builds WitnessData, WitnessRows, and WitnessCore first, facade last.
    return ([chunk_module(spec) for spec in chunk_specs()] +
            ['PanelMoments.WitnessEvaluation', 'PanelMoments.WitnessSource'])


def render_chunk(spec):
    initial = spec['initial']
    if initial is None:
        formula = 'evaluationMinor (table (R := ZMod 11))'
        residue, inverse_name = 'evaluationResidue', 'evaluationInverse'
    else:
        formula = f'sourceMinor (table (R := ZMod 11)) {initial}'
        residue, inverse_name = f'sourceResidue {initial}', f'sourceInverse {initial}'
    output = ['''import PanelMoments.WitnessCore

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option Elab.async false

/-!
Generated by `exploration/generate_lean_witness.py`.
Each theorem splits one row into scalar kernel checks. This module must be built
sequentially with the other chunks; the computations have no native oracle.
-/

namespace PanelMoments.Witness

''']
    for row in range(spec['start'], spec['stop']):
        output.append(f'''theorem {spec['prefix']}_formula_row_{row:02} :
    ({formula}) {row} = ({residue}) {row} := by
  funext j
  fin_cases j <;> decide +kernel

theorem {spec['prefix']}_inverse_row_{row:02} :
    (({residue}) * ({inverse_name})) {row} =
      (1 : Matrix (Fin {spec['size']}) (Fin {spec['size']}) (ZMod 11)) {row} := by
  funext j
  fin_cases j <;> decide +kernel

''')
    output.append('end PanelMoments.Witness\n')
    return ''.join(output)


def aggregate_header(specs, title):
    imports = '\n'.join(f'import {chunk_module(spec)}' for spec in specs)
    return f'''{imports}
import Mathlib.LinearAlgebra.Matrix.Rank

set_option autoImplicit false
set_option maxRecDepth 100000
set_option Elab.async false

/-!
# {title}

Generated by `exploration/generate_lean_witness.py`. The matrix equalities below
assemble individually kernel-checked rows, then use determinant functoriality.
Build the generated chunk modules sequentially before this aggregate.
-/

namespace PanelMoments.Witness

local instance : Fact (1 < 11) := ⟨by decide⟩

'''


def row_cases(prefix, kind, size, indent=2):
    pad = ' ' * indent
    return (f'{pad}funext i\n{pad}fin_cases i\n' +
            ''.join(f'{pad}· exact {prefix}_{kind}_row_{row:02}\n'
                    for row in range(size)))


def render_evaluation():
    specs = [spec for spec in chunk_specs() if spec['initial'] is None]
    output = [aggregate_header(specs, 'Checked evaluation minor')]
    output.append('''/-- All 2304 primitive evaluations agree with the certificate data. -/
theorem evaluationMinor_mod11 :
    evaluationMinor (table (R := ZMod 11)) = evaluationResidue := by
''')
    output.append(row_cases('evaluation', 'formula', 48))
    output.append('''
theorem evaluationResidue_inverse : evaluationResidue * evaluationInverse = 1 := by
''')
    output.append(row_cases('evaluation', 'inverse', 48))
    output.append('''
theorem evaluationMinor_mod11_det_ne_zero :
    (evaluationMinor (table (R := ZMod 11))).det ≠ 0 := by
  rw [evaluationMinor_mod11]
  exact Matrix.det_ne_zero_of_right_inverse evaluationResidue_inverse

theorem evaluationMinor_int_det_ne_zero :
    (evaluationMinor (table (R := ℤ))).det ≠ 0 := by
  intro h
  apply evaluationMinor_mod11_det_ne_zero
  have hm : (evaluationMinor (table (R := ℤ))).map (Int.castRingHom (ZMod 11)) =
      evaluationMinor (table (R := ZMod 11)) := by
    simpa only [map_table] using
      map_evaluationMinor (Int.castRingHom (ZMod 11)) (table (R := ℤ))
  calc
    _ = ((evaluationMinor (table (R := ℤ))).map (Int.castRingHom (ZMod 11))).det :=
      congrArg Matrix.det hm.symm
    _ = (Int.castRingHom (ZMod 11)) (evaluationMinor (table (R := ℤ))).det :=
      ((Int.castRingHom (ZMod 11)).map_det _).symm
    _ = 0 := by rw [h, map_zero]

noncomputable section

theorem evaluationMinor_real_det_ne_zero :
    (evaluationMinor (table (R := ℝ))).det ≠ 0 := by
  have hm : (evaluationMinor (table (R := ℤ))).map (Int.castRingHom ℝ) =
      evaluationMinor (table (R := ℝ)) := by
    simpa only [map_table] using
      map_evaluationMinor (Int.castRingHom ℝ) (table (R := ℤ))
  have hd : ((evaluationMinor (table (R := ℤ))).det : ℝ) =
      (evaluationMinor (table (R := ℝ))).det :=
    ((Int.castRingHom ℝ).map_det _).trans (congrArg Matrix.det hm)
  rw [← hd]
  exact Int.cast_ne_zero.mpr evaluationMinor_int_det_ne_zero

theorem evaluationMinor_real_rank : (evaluationMinor (table (R := ℝ))).rank = 48 := by
  simpa using Matrix.rank_of_det_ne_zero evaluationMinor_real_det_ne_zero

end

end PanelMoments.Witness
''')
    return ''.join(output)


def source_row_cases(kind):
    output = ['  fin_cases r\n']
    for initial in range(3):
        proof = row_cases(f'source{initial}', kind, 33, indent=4)
        output.append('  · ' + proof[4:])
    return ''.join(output)


def render_source():
    specs = [spec for spec in chunk_specs() if spec['initial'] is not None]
    output = [aggregate_header(specs, 'Checked source-moment minors')]
    output.append('''/-- Each initial state's data agree with the shared source-moment formula. -/
theorem sourceMinor_mod11 (r : State 2) :
    sourceMinor (table (R := ZMod 11)) r = sourceResidue r := by
''')
    output.append(source_row_cases('formula'))
    output.append('''
theorem sourceResidue_inverse (r : State 2) :
    sourceResidue r * sourceInverse r = 1 := by
''')
    output.append(source_row_cases('inverse'))
    output.append('''
theorem sourceMinor_mod11_det_ne_zero (r : State 2) :
    (sourceMinor (table (R := ZMod 11)) r).det ≠ 0 := by
  rw [sourceMinor_mod11]
  exact Matrix.det_ne_zero_of_right_inverse (sourceResidue_inverse r)

theorem sourceMinor_int_det_ne_zero (r : State 2) :
    (sourceMinor (table (R := ℤ)) r).det ≠ 0 := by
  intro h
  apply sourceMinor_mod11_det_ne_zero r
  have hm : (sourceMinor (table (R := ℤ)) r).map (Int.castRingHom (ZMod 11)) =
      sourceMinor (table (R := ZMod 11)) r := by
    simpa only [map_table] using
      map_sourceMinor (Int.castRingHom (ZMod 11)) (table (R := ℤ)) r
  calc
    _ = ((sourceMinor (table (R := ℤ)) r).map (Int.castRingHom (ZMod 11))).det :=
      congrArg Matrix.det hm.symm
    _ = (Int.castRingHom (ZMod 11)) (sourceMinor (table (R := ℤ)) r).det :=
      ((Int.castRingHom (ZMod 11)).map_det _).symm
    _ = 0 := by rw [h, map_zero]

noncomputable section

theorem sourceMinor_real_det_ne_zero (r : State 2) :
    (sourceMinor (table (R := ℝ)) r).det ≠ 0 := by
  have hm : (sourceMinor (table (R := ℤ)) r).map (Int.castRingHom ℝ) =
      sourceMinor (table (R := ℝ)) r := by
    simpa only [map_table] using
      map_sourceMinor (Int.castRingHom ℝ) (table (R := ℤ)) r
  have hd : ((sourceMinor (table (R := ℤ)) r).det : ℝ) =
      (sourceMinor (table (R := ℝ)) r).det :=
    ((Int.castRingHom ℝ).map_det _).trans (congrArg Matrix.det hm)
  rw [← hd]
  exact Int.cast_ne_zero.mpr (sourceMinor_int_det_ne_zero r)

theorem sourceMinor_real_rank (r : State 2) :
    (sourceMinor (table (R := ℝ)) r).rank = 33 := by
  simpa using Matrix.rank_of_det_ne_zero (sourceMinor_real_det_ne_zero r)

end

end PanelMoments.Witness
''')
    return ''.join(output)


def generated_files():
    output = {Path('formal/PanelMoments/WitnessData.lean'): render_data_facade(),
              Path('formal/PanelMoments/WitnessRows.lean'): render_rows()}
    for definition in data_definitions():
        output[DATA_DIRECTORY / f'{data_name(definition)}.lean'] = render_data_module(definition)
    for spec in chunk_specs():
        output[CHUNK_DIRECTORY / f'{spec["name"]}.lean'] = render_chunk(spec)
    output[Path('formal/PanelMoments/WitnessEvaluation.lean')] = render_evaluation()
    output[Path('formal/PanelMoments/WitnessSource.lean')] = render_source()
    return output


def emit(check=False):
    generated = generated_files()
    expected_chunks = {path for path in generated if path.parent == CHUNK_DIRECTORY}
    expected_data = {path for path in generated if path.parent == DATA_DIRECTORY}
    current_generated = {path.relative_to(ROOT)
                         for directory in (CHUNK_DIRECTORY, DATA_DIRECTORY)
                         for path in (ROOT / directory).glob('*.lean')}
    stale = sorted(current_generated - expected_chunks - expected_data)
    mismatches = []
    for relative, contents in generated.items():
        destination = ROOT / relative
        if check:
            if not destination.exists() or destination.read_text() != contents:
                mismatches.append(relative)
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            if not destination.exists() or destination.read_text() != contents:
                destination.write_text(contents)
    if mismatches or stale:
        issues = ([f'Generated content mismatch: {path}' for path in mismatches] +
                  [f'Stale generated module (preserved): {path}' for path in stale])
        raise SystemExit('\n'.join(issues))
    action = 'Verified' if check else 'Generated'
    print(f'{action} {len(generated)} files: 48 evaluation rows; three 33-row '
          f'source minors; modulus {PRIME}; {len(expected_data)} small data modules; '
          f'{len(expected_chunks)} cached chunks '
          f'with at most {ROWS_PER_CHUNK} rows each.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true',
                      help='verify all generated data, chunks, and aggregators without writing')
    mode.add_argument('--list-modules', action='store_true',
                      help='print chunks then aggregates; build WitnessData/Rows/Core first, facade last')
    mode.add_argument('--list-data-modules', action='store_true',
                      help='print independent data modules then data facade in sequential build order')
    args = parser.parse_args()
    if args.list_modules:
        print('\n'.join(sequential_modules()))
    elif args.list_data_modules:
        print('\n'.join(data_module_names()))
    else:
        emit(check=args.check)

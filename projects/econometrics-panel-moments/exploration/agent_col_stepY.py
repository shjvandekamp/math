#!/usr/bin/env python3
"""agent_col task 3(a): is the delta = 0 step (collision u_N = u_0) free of the head map?

At delta = 0 (blocks 0..m-1 distinct, block N = m equal to block 0) the old columns are
A = span{E_s (s < m)} + Phi_0(W_m), Phi_0(w) = w K_0 + sum Lambda_m(w)_tab h_tab (I - K_0).
Since h_tab (I - K_0) = B_{t,0,a,b} lies in W_m for t != 0, A lies in the EXPLICIT (Lambda-free) space

    Y := W_m K_0 + W_m + H_0,    H_0 := span{h_{0ab} (I - K_0)},

where W_m is generated by its canonical basis {E, B} (no P(m) needed).  The new delta = 0 columns are
F_{t,N} (t >= 1), F_{N,s} (s >= 1), F_{0,N}: 18m - 9 vectors.  If they are independent modulo Y, then
dim S_0 = dim A + 18m - 9 with a Lambda-free second summand.  This script prints
dim W_m K_0 cap W_m, dim Y, dim A, the rank of the new columns modulo Y, and dim(S_0 cap Y) - dim A.
Exact mod p = 2^61-1 at one random product-form point per n (evaluation at random X).
What this does not show: a proof of either rank statement; anything beyond the printed n.
"""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from agent_col_lib import (Q, collision_config, eval_terms_matrix, rand_points, rank, T_E, T_F)  # noqa: E402


def canon_W(m):
    """Canonical basis of W_m (blocks 0..m-1): E_{s,a}, B_{t,s,a,b} = h_tab (I - K_s)."""
    out = [T_E(s, a) for s in range(m) for a in range(Q)]
    out += [[(1, a, [(t, b)], 'IW', [s])] for t in range(m) for s in range(m) if s != t
            for a in range(Q) for b in range(Q)]
    return out


def times_K0(vec):
    """right multiplication by K_0:  e_b (I - W) K_0 = e_b K_0 - e_b W K_0  ->  terms with kind 'W'."""
    out = []
    for coef, a0, heads, kind, word in vec:
        assert kind == 'IW'
        out.append((coef, a0, heads, 'W', [0]))
        out.append((-coef, a0, heads, 'W', list(word) + [0]))
    return out


def main(ns):
    for n in ns:
        m = n - 1
        N = n - 1
        rng = random.Random(500 + n)
        A0, _ = collision_config(n, 0, rng, 1)
        Wm = canon_W(m)
        WmK = [times_K0(v) for v in Wm]
        H0 = [[(1, a, [(0, b)], 'IW', [0])] for a in range(Q) for b in range(Q)]
        Es = [T_E(s, a) for s in range(m) for a in range(Q)]
        Aold = Es + [T_F(t, s, a, b, n) for t in range(m) for s in range(m) if s != t
                     for a in range(Q) for b in range(Q)]
        new = [T_F(t, N, a, b, n) for t in range(1, m) for a in range(Q) for b in range(Q)]
        new += [T_F(N, s, a, b, n) for s in range(1, m) for a in range(Q) for b in range(Q)]
        new += [T_F(0, N, a, b, n) for a in range(Q) for b in range(Q)]
        Y = WmK + Wm + H0
        npts = (len(Y) + len(new)) // 2 + 12
        pts = rand_points(A0, npts, rng, 1)

        def dim(vs):
            return rank(eval_terms_matrix(A0, vs, pts, 1, ncomp=2))

        dWK, dW = dim(WmK), dim(Wm)
        dWKW = dim(WmK + Wm)
        dY = dim(Y)
        dA = dim(Aold)
        dAY = dim(Aold + Y)
        dYn = dim(Y + new)
        dS0 = dim(Aold + new)
        print(f'n={n} m={m}: dim W_m={dW}, dim W_m K_0={dWK}, dim(W_m K_0 cap W_m)={dWK + dW - dWKW}, '
              f'dim Y={dY}; dim A={dA} (|A|={len(Aold)}), A in Y: {dAY == dY}; '
              f'#new={len(new)} (18m-9={18 * m - 9}), rank(new mod Y)={dYn - dY}; dim S_0={dS0}; '
              f'dim(S_0 cap Y) - dim A = {dA + len(new) - (dYn - dY) - dA if dS0 == dA + len(new) else "n/a"}',
              flush=True)


if __name__ == '__main__':
    main([int(x) for x in sys.argv[1:]] or [4, 5, 6])
